/**
 * Writes `src/regex/kernelWasm.ts`: the SIMD search kernel in
 * `kernels/teddy.c`, compiled to WebAssembly with clang and embedded as
 * base64, so a build needs no C compiler.
 *
 *   node scripts/kernels.mjs
 */
import { execFileSync } from "node:child_process"
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("..", import.meta.url))
const dir = mkdtempSync(join(tmpdir(), "erg-kernels-"))
try {
  const out = join(dir, "teddy.wasm")
  execFileSync("clang", [
    "--target=wasm32",
    "-O3",
    "-msimd128",
    "-nostdlib",
    "-Wl,--no-entry",
    "-Wl,--import-memory",
    "-o",
    out,
    join(root, "kernels/teddy.c")
  ])
  const base64 = readFileSync(out).toString("base64")
  const version = execFileSync("clang", ["--version"], { encoding: "utf8" }).split("\n")[0]
  writeFileSync(
    join(root, "src/regex/kernelWasm.ts"),
    `/**
 * The SIMD search kernel (\`kernels/teddy.c\`) as WebAssembly, generated by
 * \`scripts/kernels.mjs\` with ${version}. Do not edit.
 *
 * @since 0.0.0
 */

/**
 * The module's bytes, base64-encoded.
 *
 * @since 0.0.0
 */
export const kernelWasm = "${base64}"
`
  )
} finally {
  rmSync(dir, { recursive: true, force: true })
}
