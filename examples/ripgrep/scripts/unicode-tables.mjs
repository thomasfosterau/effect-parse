/**
 * Writes `src/regex/unicodeTables.ts`: the Unicode sets `erg` uses most
 * (`\w`, `\d`, `\s`) and the simple case folding classes, computed from the
 * Unicode data of the running Node. Precomputed, they cost nothing at
 * start-up; computed, they cost tens of milliseconds per run.
 *
 *   node scripts/unicode-tables.mjs
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const MAX = 0x10ffff
const isSurrogate = (c) => c >= 0xd800 && c <= 0xdfff

/** Every Unicode scalar value, in order. */
const scalars = () => Array.from({ length: MAX + 1 }, (_, c) => c).filter((c) => !isSurrogate(c))

/** Whether `c` extends range `last` (code points are consecutive apart from the surrogates). */
const extends_ = (last, c) => last[1] + 1 === c || (last[1] === 0xd7ff && c === 0xe000)

/** Sorted code points as inclusive ranges, merging across the surrogate gap. */
const toRanges = (members) =>
  members.reduce((out, c) => {
    const last = out.at(-1)
    if (last !== undefined && extends_(last, c)) last[1] = c
    else out.push([c, c])
    return out
  }, [])

const ranges = (re) => toRanges(scalars().filter((c) => re.test(String.fromCodePoint(c))))

const single = (s) => {
  const c = s.codePointAt(0)
  return c !== undefined && String.fromCodePoint(c).length === s.length ? c : undefined
}

/** The code points `c` maps to under simple case mapping. */
const mappings = (c) => {
  const s = String.fromCodePoint(c)
  return [single(s.toLowerCase()), single(s.toUpperCase())].filter((m) => m !== undefined && m !== c)
}

/** A union-find over code points. */
const unionFind = () => {
  const parent = new Map()
  const find = (c) => {
    let r = c
    while (parent.has(r) && parent.get(r) !== r) r = parent.get(r)
    return r
  }
  const join = (a, b) => {
    const ra = find(a)
    const rb = find(b)
    parent.set(a, a === ra ? rb : parent.get(a))
    if (!parent.has(b)) parent.set(b, b)
    if (ra !== rb) parent.set(ra, rb)
  }
  return { find, join, members: () => [...parent.keys()] }
}

const foldClasses = () => {
  const sets = unionFind()
  const cased = /^\p{Changes_When_Casemapped}$/u
  for (const c of scalars().filter((c) => cased.test(String.fromCodePoint(c)))) {
    for (const m of mappings(c)) sets.join(c, m)
  }
  const groups = Map.groupBy(sets.members(), sets.find)
  return [...groups.values()]
    .filter((g) => g.length > 1)
    .map((g) => g.toSorted((a, b) => a - b))
    .toSorted((a, b) => a[0] - b[0])
}

const json = (x) => JSON.stringify(x)
const source = `/**
 * Unicode tables for the regex engine, generated by
 * \`scripts/unicode-tables.mjs\` from the Unicode data of Node ${process.version}
 * (Unicode ${process.versions.unicode}). Do not edit.
 *
 * @since 0.0.0
 */

/**
 * Rust's \`\\w\`: \`Alphabetic\`, marks, decimal numbers, connector punctuation and \`Join_Control\`.
 *
 * @since 0.0.0
 */
export const word: ReadonlyArray<readonly [number, number]> = ${json(ranges(/^[\p{Alphabetic}\p{M}\p{Nd}\p{Pc}\p{Join_Control}]$/u))}

/**
 * Rust's \`\\d\`: general category \`Nd\`.
 *
 * @since 0.0.0
 */
export const digit: ReadonlyArray<readonly [number, number]> = ${json(ranges(/^\p{Nd}$/u))}

/**
 * Rust's \`\\s\`: \`White_Space\`.
 *
 * @since 0.0.0
 */
export const space: ReadonlyArray<readonly [number, number]> = ${json(ranges(/^\p{White_Space}$/u))}

/**
 * The classes of simple case folding with more than one member.
 *
 * @since 0.0.0
 */
export const foldClasses: ReadonlyArray<ReadonlyArray<number>> = ${json(foldClasses())}
`
writeFileSync(fileURLToPath(new URL("../src/regex/unicodeTables.ts", import.meta.url)), source)
